function utils_showMessage(message, type, errorDetails)
% utils_showMessage  显示消息提示
%
% 用法:
%   utils_showMessage('操作成功', 'success')           % 成功消息，0.5秒后自动消失
%   utils_showMessage('操作失败', 'error', ME.message) % 错误消息，需要手动确认
%
% 参数:
%   message      - 主要消息文本
%   type         - 消息类型: 'success' 或 'error'
%   errorDetails - (可选) 错误详细信息，仅用于 error 类型

if nargin < 2
    type = 'success';
end

if nargin < 3
    errorDetails = '';
end

switch lower(type)
    case 'success'
        % 成功消息：绿色背景，0.5秒后自动关闭
        fig = figure('Name', '提示', ...
                    'NumberTitle', 'off', ...
                    'MenuBar', 'none', ...
                    'ToolBar', 'none', ...
                    'Position', [0, 0, 350, 100], ...
                    'Color', [0.9, 1, 0.9], ...
                    'Resize', 'off', ...
                    'WindowStyle', 'modal');
        
        % 居中显示
        movegui(fig, 'center');
        
        % 成功图标和消息
        uicontrol('Parent', fig, ...
                 'Style', 'text', ...
                 'String', '✓', ...
                 'Position', [20, 30, 40, 40], ...
                 'FontSize', 32, ...
                 'FontWeight', 'bold', ...
                 'ForegroundColor', [0, 0.6, 0], ...
                 'BackgroundColor', [0.9, 1, 0.9], ...
                 'HorizontalAlignment', 'center');
        
        uicontrol('Parent', fig, ...
                 'Style', 'text', ...
                 'String', message, ...
                 'Position', [70, 20, 260, 60], ...
                 'FontSize', 12, ...
                 'FontWeight', 'bold', ...
                 'ForegroundColor', [0, 0.4, 0], ...
                 'BackgroundColor', [0.9, 1, 0.9], ...
                 'HorizontalAlignment', 'left');
        
        % 0.5秒后自动关闭
        pause(0.5);
        if ishandle(fig)
            delete(fig);
        end
        
    case 'error'
        % 错误消息：红色背景，需要手动确认
        screenSize = get(0, 'ScreenSize');
        figWidth = 450;
        figHeight = 200;
        
        if ~isempty(errorDetails)
            figHeight = 280;
        end
        
        fig = figure('Name', '错误', ...
                    'NumberTitle', 'off', ...
                    'MenuBar', 'none', ...
                    'ToolBar', 'none', ...
                    'Position', [(screenSize(3)-figWidth)/2, (screenSize(4)-figHeight)/2, figWidth, figHeight], ...
                    'Color', [1, 0.95, 0.95], ...
                    'Resize', 'off', ...
                    'WindowStyle', 'modal');
        
        % 错误图标
        uicontrol('Parent', fig, ...
                 'Style', 'text', ...
                 'String', '✗', ...
                 'Position', [20, figHeight-80, 50, 50], ...
                 'FontSize', 36, ...
                 'FontWeight', 'bold', ...
                 'ForegroundColor', [0.8, 0, 0], ...
                 'BackgroundColor', [1, 0.95, 0.95], ...
                 'HorizontalAlignment', 'center');
        
        % 错误消息
        uicontrol('Parent', fig, ...
                 'Style', 'text', ...
                 'String', message, ...
                 'Position', [80, figHeight-80, 350, 50], ...
                 'FontSize', 12, ...
                 'FontWeight', 'bold', ...
                 'ForegroundColor', [0.6, 0, 0], ...
                 'BackgroundColor', [1, 0.95, 0.95], ...
                 'HorizontalAlignment', 'left');
        
        % 错误详情（如果有）
        if ~isempty(errorDetails)
            uicontrol('Parent', fig, ...
                     'Style', 'text', ...
                     'String', '错误详情:', ...
                     'Position', [20, figHeight-130, 100, 20], ...
                     'FontSize', 10, ...
                     'FontWeight', 'bold', ...
                     'ForegroundColor', [0.3, 0, 0], ...
                     'BackgroundColor', [1, 0.95, 0.95], ...
                     'HorizontalAlignment', 'left');
            
            uicontrol('Parent', fig, ...
                     'Style', 'text', ...
                     'String', errorDetails, ...
                     'Position', [20, 60, 410, 60], ...
                     'FontSize', 9, ...
                     'ForegroundColor', [0.4, 0, 0], ...
                     'BackgroundColor', [1, 1, 1], ...
                     'HorizontalAlignment', 'left');
        end
        
        % 确定按钮
        uicontrol('Parent', fig, ...
                 'Style', 'pushbutton', ...
                 'String', '确定', ...
                 'Position', [(figWidth-100)/2, 15, 100, 35], ...
                 'FontSize', 11, ...
                 'FontWeight', 'bold', ...
                 'BackgroundColor', [0.8, 0.2, 0.2], ...
                 'ForegroundColor', [1, 1, 1], ...
                 'Callback', @(~,~) delete(fig));
        
        % 等待用户点击
        uiwait(fig);
        
    otherwise
        warning('未知的消息类型: %s', type);
end

end
