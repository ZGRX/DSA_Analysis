function doctorInfo = login_doctor()
% 医生登录界面
% 返回: doctorInfo 结构体 (包含 name, id) 或 空 (如果取消/失败)

doctorInfo = [];
isVerified = false;

% 创建登录窗口
screenSize = get(0, 'ScreenSize');
dlgWidth = 400;
dlgHeight = 280;
xPos = (screenSize(3) - dlgWidth) / 2;
yPos = (screenSize(4) - dlgHeight) / 2;

hFig = figure('Name', '医生登录 - DSA分析系统', ...
    'Position', [xPos, yPos, dlgWidth, dlgHeight], ...
    'MenuBar', 'none', ...
    'ToolBar', 'none', ...
    'NumberTitle', 'off', ...
    'Resize', 'off', ...
    'Color', [0.95, 0.97, 1], ...
    'WindowStyle', 'normal'); % 改为普通窗口以避免焦点问题

% 标题
uicontrol('Parent', hFig, 'Style', 'text', ...
    'String', 'DSA 脑血流分析系统', ...
    'Position', [0, 220, 400, 40], ...
    'FontSize', 18, 'FontWeight', 'bold', ...
    'FontName', 'Microsoft YaHei', ...
    'ForegroundColor', [0.2, 0.5, 0.7], ...
    'BackgroundColor', [0.95, 0.97, 1], ...
    'HorizontalAlignment', 'center');

uicontrol('Parent', hFig, 'Style', 'text', ...
    'String', '医师登录 / Doctor Login', ...
    'Position', [0, 190, 400, 25], ...
    'FontSize', 11, ...
    'FontName', 'Microsoft YaHei', ...
    'ForegroundColor', [0.4, 0.4, 0.4], ...
    'BackgroundColor', [0.95, 0.97, 1], ...
    'HorizontalAlignment', 'center');

% 用户名
uicontrol('Parent', hFig, 'Style', 'text', ...
    'String', '账号:', ...
    'Position', [60, 140, 60, 25], ...
    'FontSize', 11, ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.95, 0.97, 1], ...
    'HorizontalAlignment', 'right');

hUser = uicontrol('Parent', hFig, 'Style', 'edit', ...
    'String', '', ...
    'Position', [130, 142, 180, 25], ...
    'FontSize', 11, ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [1, 1, 1]); % 显式白色背景

% 密码
uicontrol('Parent', hFig, 'Style', 'text', ...
    'String', '密码:', ...
    'Position', [60, 95, 60, 25], ...
    'FontSize', 11, ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.95, 0.97, 1], ...
    'HorizontalAlignment', 'right');

hPass = uicontrol('Parent', hFig, 'Style', 'edit', ...
    'String', '', ...
    'Position', [130, 97, 180, 25], ...
    'FontSize', 11, ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [1, 1, 1]); % 移除了可能导致冲突的 Callback

% 存储真实密码
setappdata(hFig, 'realPassword', '');

% 登录按钮
hBtn = uicontrol('Parent', hFig, 'Style', 'pushbutton', ...
    'String', '登 录', ...
    'Position', [130, 40, 180, 35], ...
    'FontSize', 12, 'FontWeight', 'bold', ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.2, 0.6, 0.9], ...
    'ForegroundColor', [1, 1, 1], ...
    'Callback', @doLogin);

% 默认焦点
uicontrol(hUser);

% 等待用户操作
uiwait(hFig);

% 回调函数
    function doLogin(~, ~)
        user = get(hUser, 'String');
        pass = get(hPass, 'String');
        
        if isempty(user)
            msgbox('请输入账号', '提示', 'warn');
            return;
        end
        
        % 按钮变成加载状态以防在生成主界面时发生视觉断层
        set(hBtn, 'String', '验证中...', 'BackgroundColor', [0.5 0.5 0.5]);
        drawnow;
        
        [isValid, doctorName] = auth_manager(user, pass);
        
        if isValid
            set(hBtn, 'String', '登录成功, 加载组件中...', 'BackgroundColor', [0.2 0.7 0.3]);
            drawnow;
            
            doctorInfo.username = user;
            doctorInfo.name = doctorName;
            doctorInfo.loginTime = char(datetime('now'));
            isVerified = true;
            
            % 暂停很短时间让用户看到成功提示，然后关闭并继续主脚本
            pause(0.3);
            delete(hFig);
        else
            set(hBtn, 'String', '登 录', 'BackgroundColor', [0.2, 0.6, 0.9]);
            errordlg('账号或密码错误', '登录失败');
        end
    end

% 处理窗口关闭
if ~isVerified
    doctorInfo = [];
end
end
