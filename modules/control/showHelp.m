function showHelp(~,~)
    % 下载帮助文档为文本文件
    
    helpContent = [...
        'DSA脑血流灌注分析系统 - 使用说明文档\n' ...
        '版本: v3.0\n' ...
        '生成时间: ' datestr(now) '\n' ...
        '========================================\n\n' ...
        '一、系统简介\n' ...
        '本系统用于DSA（数字减影血管造影）脑血流灌注分析，可评估术前术后血流变化，\n' ...
        '预警高灌注风险，为临床决策提供定量依据。\n\n' ...
        '二、操作流程\n' ...
        '1. 导入DSA数据\n' ...
        '   - 点击"导入DSA数据"按钮\n' ...
        '   - 选择DICOM格式的DSA图像序列文件\n' ...
        '   - 系统自动识别帧数和图像尺寸\n\n' ...
        '2. 放置ROI（感兴趣区域）\n' ...
        '   - 点击"放置ROI"按钮\n' ...
        '   - 依次为额叶、顶叶、颞叶、枕叶各选择3个点（共12个）\n' ...
        '   - 左键点击放置ROI，右键点击撤销上一个ROI\n' ...
        '   - 注意：避开大血管，选择脑实质区域\n\n' ...
        '3. 提取并分析TDC（时间密度曲线）\n' ...
        '   - 点击"提取并分析TDC"按钮\n' ...
        '   - 系统自动提取所有ROI的时间序列数据\n' ...
        '   - 自动进行Hermite多项式插值平滑\n' ...
        '   - 计算11个灌注参数（TMAX, MTT, TU, TD等）\n' ...
        '   - 参数表格显示在右侧面板\n\n' ...
        '4. 显示分析结果\n' ...
        '   - 点击"显示结果"按钮\n' ...
        '   - 查看原始曲线、平滑曲线、参数对比图表\n' ...
        '   - 分析各脑叶灌注参数的相关性\n\n' ...
        '5. 导出数据\n' ...
        '   - 点击"导出数据"按钮\n' ...
        '   - 支持导出MAT、Excel、CSV格式\n' ...
        '   - 包含所有灌注参数和时间序列数据\n\n' ...
        '6. 术前术后对比分析\n' ...
        '   - 点击"术前术后对比"按钮\n' ...
        '   - 导入术前和术后的MAT数据文件\n' ...
        '   - 系统自动计算血流速度增加比例\n' ...
        '   - 根据TCD标准评估高灌注风险\n\n' ...
        '三、高灌注风险预警标准（基于TCD标准）\n' ...
        '- 高风险: 术后血流速度增加 ≥ 150%\n' ...
        '  建议：密切监测，控制血压，考虑预防性药物治疗\n' ...
        '- 中风险: 术后血流速度增加 120%-150%\n' ...
        '  建议：定期监测血压，观察神经症状变化\n' ...
        '- 低风险: 术后血流速度增加 < 120%\n' ...
        '  建议：常规术后观察，维持血压稳定\n\n' ...
        '四、灌注参数说明\n' ...
        'TMAX (s)      - 峰值时间：曲线达到最大值的时间\n' ...
        'MTT (s)       - 平均通过时间：对比剂通过ROI的平均时间\n' ...
        'TU (s)        - 上升时间：从基线到峰值的时间\n' ...
        'TD (s)        - 到达时间：对比剂到达ROI的时间\n' ...
        '1/2TMAX (s)   - 半峰时间：曲线达到半峰值的时间\n' ...
        'AUC           - 曲线下面积：反映血流灌注总量\n' ...
        'AUCbefore     - 峰值前面积\n' ...
        'AUCbefore/AUC - 峰值前面积比例\n' ...
        'MS (SI/s)     - 最大斜率：曲线上升最快速率\n' ...
        'AFS (SI/s)    - 平均上升斜率\n' ...
        'CBF (SI)      - 脑血流量估算值\n\n' ...
        '五、帧控制功能\n' ...
        '- 滑块：快速浏览不同时间帧\n' ...
        '- 播放/暂停：动态播放DSA序列\n' ...
        '- 导航按钮：快速跳转到首帧、末帧、上一帧、下一帧\n' ...
        '- 帧范围选择：设置分析的起始和结束帧\n\n' ...
        '六、注意事项\n' ...
        '1. 数据要求\n' ...
        '   - DICOM格式的DSA图像序列\n' ...
        '   - 建议包含至少20帧以上数据\n' ...
        '   - 图像质量应清晰，无明显伪影\n\n' ...
        '2. ROI放置技巧\n' ...
        '   - 避开大血管和明显的血管影\n' ...
        '   - 选择脑实质区域，确保代表性\n' ...
        '   - 每个脑叶的3个ROI应分散分布\n' ...
        '   - 可使用右键撤销功能调整位置\n\n' ...
        '3. 帧率设置\n' ...
        '   - 默认帧率为4 fps\n' ...
        '   - 应根据实际采集参数调整\n' ...
        '   - 帧率影响时间参数的准确性\n\n' ...
        '4. 对比分析流程\n' ...
        '   - 先完成术前数据分析并导出MAT文件\n' ...
        '   - 再完成术后数据分析并导出MAT文件\n' ...
        '   - 使用"术前术后对比"功能导入两个文件\n' ...
        '   - 系统自动生成风险评估报告\n\n' ...
        '七、常见问题\n' ...
        'Q: 提示"请先导入图像"？\n' ...
        'A: 需要先使用"导入DSA数据"导入DICOM文件。\n\n' ...
        'Q: 参数表显示-Inf或N/A？\n' ...
        'A: 可能是ROI位置不佳或数据质量问题，建议重新放置ROI。\n\n' ...
        'Q: 如何撤销ROI？\n' ...
        'A: 在放置ROI过程中，使用鼠标右键点击可撤销上一个ROI。\n\n' ...
        'Q: 导出的Excel文件包含哪些内容？\n' ...
        'A: 包含灌注参数表、时间序列数据和分析信息三个工作表。\n\n' ...
        '八、技术支持\n' ...
        '如有问题或建议，请联系开发团队。\n' ...
        '========================================\n' ...
        '文档结束\n'
    ];
    
    % 弹出保存对话框
    [file, path] = uiputfile({'*.txt', '文本文件 (*.txt)'; '*.md', 'Markdown文件 (*.md)'}, ...
                             '保存使用帮助文档', ...
                             ['DSA分析系统使用说明_' datestr(now, 'yyyymmdd') '.txt']);
    
    if isequal(file, 0)
        % 用户取消
        return;
    end
    
    try
        % 写入文件
        fullPath = fullfile(path, file);
        fid = fopen(fullPath, 'w', 'n', 'UTF-8');
        if fid == -1
            utils_showMessage('无法创建帮助文档', 'error', '文件写入权限不足或路径无效');
            return;
        end
        
        fprintf(fid, '%s', helpContent);
        fclose(fid);
        
        utils_showMessage(sprintf('帮助文档已保存至:\n%s', fullPath), 'success');
        log_addWorkLog(sprintf('帮助文档已导出: %s', file));
        
    catch ME
        utils_showMessage('帮助文档保存失败', 'error', ME.message);
    end
end
