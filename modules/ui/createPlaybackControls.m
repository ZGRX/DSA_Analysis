function createPlaybackControls(parent)
% 创建播放和帧控制区域
% 输入: parent - 父容器句柄（通常是 displayPanel）

% 创建帧控制面板（位于显示区域下方，现代医疗风格）
controlPanel = uipanel('Parent', parent, ...
    'Title', '帧播放控制 / Playback', ...
    'Units', 'normalized', ...
    'Position', [0.02, 0.01, 0.96, 0.12], ...
    'BackgroundColor', [0.97, 0.98, 1], ...
    'ForegroundColor', [0.2, 0.5, 0.7], ...
    'FontSize', 10, ...
    'FontName', 'Microsoft YaHei', ...
    'FontWeight', 'bold');

% 第一行：播放功能区 (播放/暂停 + 帧导航 + 帧率)
% 播放
playBtn = uicontrol('Parent', controlPanel, ...
    'Style', 'pushbutton', ...
    'String', '▶ 播放', ...
    'Units', 'normalized', ...
    'Position', [0.01, 0.55, 0.10, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.35, 0.75, 0.45], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @togglePlayback);

% 暂停
pauseBtn = uicontrol('Parent', controlPanel, ...
    'Style', 'pushbutton', ...
    'String', '⏸ 暂停', ...
    'Units', 'normalized', ...
    'Position', [0.12, 0.55, 0.10, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.6, 0.6, 0.6], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @stopPlayback);

% 导航组 (紧凑排列)
firstFrameBtn = uicontrol('Parent', controlPanel, 'Style', 'pushbutton', 'String', '|<<', ...
    'Units', 'normalized', 'Position', [0.24, 0.55, 0.06, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'BackgroundColor', [0.3, 0.65, 0.92], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @goToFirstFrame);

prevFrameBtn = uicontrol('Parent', controlPanel, 'Style', 'pushbutton', 'String', '<', ...
    'Units', 'normalized', 'Position', [0.31, 0.55, 0.06, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'BackgroundColor', [0.3, 0.65, 0.92], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @goToPrevFrame);

nextFrameBtn = uicontrol('Parent', controlPanel, 'Style', 'pushbutton', 'String', '>', ...
    'Units', 'normalized', 'Position', [0.38, 0.55, 0.06, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'BackgroundColor', [0.3, 0.65, 0.92], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @goToNextFrame);

lastFrameBtn = uicontrol('Parent', controlPanel, 'Style', 'pushbutton', 'String', '>>|', ...
    'Units', 'normalized', 'Position', [0.45, 0.55, 0.06, 0.35], ...
    'FontSize', 10, 'FontWeight', 'bold', 'BackgroundColor', [0.3, 0.65, 0.92], 'ForegroundColor', [1, 1, 1], ...
    'Enable', 'off', 'Callback', @goToLastFrame);

% 帧率 (右对齐)
uicontrol('Parent', controlPanel, 'Style', 'text', 'String', '帧率(fps):', ...
    'Units', 'normalized', 'Position', [0.75, 0.55, 0.12, 0.30], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', 'HorizontalAlignment', 'right', ...
    'BackgroundColor', [0.97, 0.98, 1]);

frameRateEdit = uicontrol('Parent', controlPanel, 'Style', 'edit', 'String', '4', ...
    'Units', 'normalized', 'Position', [0.88, 0.57, 0.08, 0.32], ...
    'FontSize', 10, 'FontName', 'Microsoft YaHei', 'BackgroundColor', [1, 1, 1], 'Enable', 'off');

% 第二行：进度条与状态 (Frame Display + Slider + Range)
% Frame X / Y (整合为一个文本框，简洁)
uicontrol('Parent', controlPanel, 'Style', 'text', 'String', 'Frame:', ...
    'Units', 'normalized', 'Position', [0.01, 0.10, 0.08, 0.30], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', 'HorizontalAlignment', 'right', 'BackgroundColor', [0.97, 0.98, 1]);

currentFrameText = uicontrol('Parent', controlPanel, 'Style', 'text', 'String', '1', ...
    'Units', 'normalized', 'Position', [0.10, 0.10, 0.05, 0.30], ...
    'FontSize', 10, 'FontWeight', 'bold', 'FontName', 'Microsoft YaHei', ...
    'ForegroundColor', [0.2, 0.7, 0.3], 'BackgroundColor', [0.97, 0.98, 1]);

uicontrol('Parent', controlPanel, 'Style', 'text', 'String', '/', ...
    'Units', 'normalized', 'Position', [0.15, 0.10, 0.02, 0.30], ...
    'FontSize', 9, 'BackgroundColor', [0.97, 0.98, 1]);

totalFramesText = uicontrol('Parent', controlPanel, 'Style', 'text', 'String', '1', ...
    'Units', 'normalized', 'Position', [0.17, 0.10, 0.05, 0.30], ...
    'FontSize', 10, 'FontName', 'Microsoft YaHei', 'BackgroundColor', [0.97, 0.98, 1]);

% 滑块 (拉长)
frameSlider = uicontrol('Parent', controlPanel, 'Style', 'slider', ...
    'Min', 1, 'Max', 100, 'Value', 1, ...
    'Units', 'normalized', 'Position', [0.24, 0.12, 0.45, 0.28], ...
    'Enable', 'off', 'Callback', @updateFrameFromSlider);

% 范围设置 (右侧，调整对齐)
uicontrol('Parent', controlPanel, 'Style', 'text', 'String', 'Range:', ...
    'Units', 'normalized', 'Position', [0.70, 0.10, 0.08, 0.30], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', 'HorizontalAlignment', 'right', 'BackgroundColor', [0.97, 0.98, 1]);

startFrameEdit = uicontrol('Parent', controlPanel, 'Style', 'edit', 'String', '1', ...
    'Units', 'normalized', 'Position', [0.79, 0.12, 0.08, 0.28], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', 'BackgroundColor', [1, 1, 1], 'Enable', 'off', 'Callback', @applyFrameRange);

uicontrol('Parent', controlPanel, 'Style', 'text', 'String', '-', ...
    'Units', 'normalized', 'Position', [0.87, 0.10, 0.02, 0.30], ...
    'FontSize', 9, 'BackgroundColor', [0.97, 0.98, 1], 'HorizontalAlignment', 'center');

endFrameEdit = uicontrol('Parent', controlPanel, 'Style', 'edit', 'String', '1', ...
    'Units', 'normalized', 'Position', [0.89, 0.12, 0.08, 0.28], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', 'BackgroundColor', [1, 1, 1], 'Enable', 'off', 'Callback', @applyFrameRange);

% 存储所有控件句柄到主窗口
fig = gcf;
setappdata(fig, 'playBtn', playBtn);
setappdata(fig, 'pauseBtn', pauseBtn);
setappdata(fig, 'firstFrameBtn', firstFrameBtn);
setappdata(fig, 'prevFrameBtn', prevFrameBtn);
setappdata(fig, 'nextFrameBtn', nextFrameBtn);
setappdata(fig, 'lastFrameBtn', lastFrameBtn);
setappdata(fig, 'frameSlider', frameSlider);
setappdata(fig, 'currentFrameText', currentFrameText);
setappdata(fig, 'totalFramesText', totalFramesText);
setappdata(fig, 'startFrameEdit', startFrameEdit);
setappdata(fig, 'endFrameEdit', endFrameEdit);
setappdata(fig, 'frameRateEdit', frameRateEdit);

% 初始化播放状态
setappdata(fig, 'isPlaying', false);
setappdata(fig, 'playTimer', []);
end
