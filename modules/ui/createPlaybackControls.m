function createPlaybackControls(parent)
    % 创建播放和帧控制区域
    % 输入: parent - 父容器句柄（通常是 displayPanel）
    
    % 创建帧控制面板（位于显示区域下方，现代医疗风格）
    controlPanel = uipanel('Parent', parent, ...
                          'Title', '帧控制', ...
                          'Units', 'normalized', ...
                          'Position', [0.02, 0.01, 0.96, 0.12], ...
                          'BackgroundColor', [0.97, 0.98, 1], ...
                          'ForegroundColor', [0.2, 0.5, 0.7], ...
                          'FontSize', 10, ...
                          'FontWeight', 'bold');
    
    % 第一行：播放控制按钮（现代配色）
    playBtn = uicontrol('Parent', controlPanel, ...
                       'Style', 'pushbutton', ...
                       'String', '播放', ...
                       'Units', 'normalized', ...
                       'Position', [0.02, 0.55, 0.12, 0.35], ...
                       'FontSize', 10, ...
                       'FontWeight', 'bold', ...
                       'BackgroundColor', [0.35, 0.75, 0.45], ...
                       'ForegroundColor', [1, 1, 1], ...
                       'Enable', 'off', ...
                       'Callback', @togglePlayback);
    
    pauseBtn = uicontrol('Parent', controlPanel, ...
                        'Style', 'pushbutton', ...
                        'String', '暂停', ...
                        'Units', 'normalized', ...
                        'Position', [0.15, 0.55, 0.12, 0.35], ...
                        'FontSize', 10, ...
                        'FontWeight', 'bold', ...
                        'BackgroundColor', [0.6, 0.6, 0.6], ...
                        'ForegroundColor', [1, 1, 1], ...
                        'Enable', 'off', ...
                        'Callback', @stopPlayback);
    
    % 帧导航按钮（现代浅蓝色）
    firstFrameBtn = uicontrol('Parent', controlPanel, ...
                             'Style', 'pushbutton', ...
                             'String', '<<', ...
                             'Units', 'normalized', ...
                             'Position', [0.29, 0.55, 0.08, 0.35], ...
                             'FontSize', 10, ...
                             'FontWeight', 'bold', ...
                             'BackgroundColor', [0.3, 0.65, 0.92], ...
                             'ForegroundColor', [1, 1, 1], ...
                             'Enable', 'off', ...
                             'Callback', @goToFirstFrame);
    
    prevFrameBtn = uicontrol('Parent', controlPanel, ...
                            'Style', 'pushbutton', ...
                            'String', '<', ...
                            'Units', 'normalized', ...
                            'Position', [0.38, 0.55, 0.08, 0.35], ...
                            'FontSize', 10, ...
                            'FontWeight', 'bold', ...
                            'BackgroundColor', [0.3, 0.65, 0.92], ...
                            'ForegroundColor', [1, 1, 1], ...
                            'Enable', 'off', ...
                            'Callback', @goToPrevFrame);
    
    nextFrameBtn = uicontrol('Parent', controlPanel, ...
                            'Style', 'pushbutton', ...
                            'String', '>', ...
                            'Units', 'normalized', ...
                            'Position', [0.47, 0.55, 0.08, 0.35], ...
                            'FontSize', 10, ...
                            'FontWeight', 'bold', ...
                            'BackgroundColor', [0.3, 0.65, 0.92], ...
                            'ForegroundColor', [1, 1, 1], ...
                            'Enable', 'off', ...
                            'Callback', @goToNextFrame);
    
    lastFrameBtn = uicontrol('Parent', controlPanel, ...
                            'Style', 'pushbutton', ...
                            'String', '>>', ...
                            'Units', 'normalized', ...
                            'Position', [0.56, 0.55, 0.08, 0.35], ...
                            'FontSize', 10, ...
                            'FontWeight', 'bold', ...
                            'BackgroundColor', [0.3, 0.65, 0.92], ...
                            'ForegroundColor', [1, 1, 1], ...
                            'Enable', 'off', ...
                            'Callback', @goToLastFrame);
    
    % 帧率设置
    uicontrol('Parent', controlPanel, ...
             'Style', 'text', ...
             'String', '帧率(fps):', ...
             'Units', 'normalized', ...
             'Position', [0.67, 0.55, 0.12, 0.30], ...
             'FontSize', 9, ...
             'ForegroundColor', [0.2, 0.3, 0.4], ...
             'BackgroundColor', [0.97, 0.98, 1], ...
             'HorizontalAlignment', 'right');
    
    frameRateEdit = uicontrol('Parent', controlPanel, ...
                             'Style', 'edit', ...
                             'String', '4', ...
                             'Units', 'normalized', ...
                             'Position', [0.80, 0.57, 0.08, 0.32], ...
                             'FontSize', 10, ...
                             'BackgroundColor', [1, 1, 1], ...
                             'Enable', 'off');
    
    % 第二行：帧滑块和当前帧显示（现代配色）
    uicontrol('Parent', controlPanel, ...
             'Style', 'text', ...
             'String', '当前帧:', ...
             'Units', 'normalized', ...
             'Position', [0.02, 0.10, 0.10, 0.30], ...
             'FontSize', 9, ...
             'ForegroundColor', [0.2, 0.3, 0.4], ...
             'BackgroundColor', [0.97, 0.98, 1], ...
             'HorizontalAlignment', 'right');
    
    currentFrameText = uicontrol('Parent', controlPanel, ...
                                'Style', 'text', ...
                                'String', '1', ...
                                'Units', 'normalized', ...
                                'Position', [0.13, 0.10, 0.06, 0.30], ...
                                'FontSize', 10, ...
                                'FontWeight', 'bold', ...
                                'ForegroundColor', [0.2, 0.7, 0.3], ...
                                'BackgroundColor', [0.97, 0.98, 1]);
    
    uicontrol('Parent', controlPanel, ...
             'Style', 'text', ...
             'String', '/', ...
             'Units', 'normalized', ...
             'Position', [0.19, 0.10, 0.02, 0.30], ...
             'FontSize', 9, ...
             'ForegroundColor', [0.2, 0.3, 0.4], ...
             'BackgroundColor', [0.97, 0.98, 1]);
    
    totalFramesText = uicontrol('Parent', controlPanel, ...
                               'Style', 'text', ...
                               'String', '1', ...
                               'Units', 'normalized', ...
                               'Position', [0.21, 0.10, 0.06, 0.30], ...
                               'FontSize', 10, ...
                               'ForegroundColor', [0.2, 0.3, 0.4], ...
                               'BackgroundColor', [0.97, 0.98, 1]);
    
    % 帧滑块
    frameSlider = uicontrol('Parent', controlPanel, ...
                           'Style', 'slider', ...
                           'Min', 1, 'Max', 100, 'Value', 1, ...
                           'Units', 'normalized', ...
                           'Position', [0.29, 0.12, 0.40, 0.28], ...
                           'Enable', 'off', ...
                           'Callback', @updateFrameFromSlider);
    
    % 帧范围设置
    uicontrol('Parent', controlPanel, ...
             'Style', 'text', ...
             'String', '起始:', ...
             'Units', 'normalized', ...
             'Position', [0.71, 0.10, 0.08, 0.30], ...
             'FontSize', 9, ...
             'ForegroundColor', [0.2, 0.3, 0.4], ...
             'BackgroundColor', [0.97, 0.98, 1], ...
             'HorizontalAlignment', 'right');
    
    startFrameEdit = uicontrol('Parent', controlPanel, ...
                              'Style', 'edit', ...
                              'String', '1', ...
                              'Units', 'normalized', ...
                              'Position', [0.80, 0.12, 0.07, 0.28], ...
                              'FontSize', 9, ...
                              'BackgroundColor', [1, 1, 1], ...
                              'Enable', 'off', ...
                              'Callback', @applyFrameRange);
    
    uicontrol('Parent', controlPanel, ...
             'Style', 'text', ...
             'String', '结束:', ...
             'Units', 'normalized', ...
             'Position', [0.84, 0.10, 0.04, 0.30], ...
             'FontSize', 9, ...
             'ForegroundColor', [0.2, 0.3, 0.4], ...
             'BackgroundColor', [0.97, 0.98, 1], ...
             'HorizontalAlignment', 'right');
    
    endFrameEdit = uicontrol('Parent', controlPanel, ...
                            'Style', 'edit', ...
                            'String', '1', ...
                            'Units', 'normalized', ...
                            'Position', [0.88, 0.12, 0.11, 0.28], ...
                            'FontSize', 9, ...
                            'BackgroundColor', [1, 1, 1], ...
                            'Enable', 'off', ...
                            'Callback', @applyFrameRange);
    
    % 存储所有控件句柄到主窗口
    fig = gcf;
    setappdata(fig, 'playBtn', playBtn);
    setappdata(fig, 'pauseBtn', pauseBtn);
    setappdata(fig, 'firstFrameBtn', firstFrameBtn);
    setappdata(fig, 'prevFrameBtn', prevFrameBtn);
    setappdata(fig, 'nextFrameBtn', nextFrameBtn);
    setappdata(fig, 'lastFrameBtn', lastFrameBtn);
    setappdata(fig, 'frameSlider', frameSlider);
    setappdata(fig, 'currentFrameText', currentFrameText);
    setappdata(fig, 'totalFramesText', totalFramesText);
    setappdata(fig, 'startFrameEdit', startFrameEdit);
    setappdata(fig, 'endFrameEdit', endFrameEdit);
    setappdata(fig, 'frameRateEdit', frameRateEdit);
    
    % 初始化播放状态
    setappdata(fig, 'isPlaying', false);
    setappdata(fig, 'playTimer', []);
end
