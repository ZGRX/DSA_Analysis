function createControlButtons(parent)
% 创建左侧控制按钮面板（现代医疗风格）

% 1. 配置区域布局参数
margins = 0.02;     % 边距
headerH = 0.04;     % 标题高度
btnH    = 0.05;     % 按钮高度
gap     = 0.01;     % 控件间距
sectGap = 0.03;     % 组间距

% 面板主标题
uicontrol('Parent', parent, 'Style', 'text', ...
    'String', '分析流程 | Control', ...
    'Units', 'normalized', ...
    'Position', [margins, 0.95, 1-2*margins, 0.04], ...
    'FontSize', 14, 'FontWeight', 'bold', ...
    'FontName', 'Microsoft YaHei', ...
    'ForegroundColor', [0.2, 0.4, 0.6], ...
    'BackgroundColor', [1, 1, 1], ...
    'HorizontalAlignment', 'center');

% 2. 定义所有按钮组（从上到下排列）
% 结构：{ '组标题', { {'按钮1', @cb1, [Color]}, {'按钮2', @cb2, [Color]}... } }
sections = {
    {'数据管理 / Data', {
    {'📁 打开文件', @createFileManagerDialog, [0.3, 0.65, 0.92]}, ...
    {'📤 导出报告', @io_exportData, [0.5, 0.5, 0.65]}, ...
    {'📊 术前术后对比', @analysis_comparePrePost, [0.92, 0.4, 0.4]}
    }}, ...
    {'ROI 分析 / Analysis', {
    {'🎯 放置 ROI', @analysis_placeROI, [0.35, 0.75, 0.45]}, ...
    {'📈 提取 TDC 曲线', @analysis_extractAndAnalyze, [0.95, 0.65, 0.25]}
    }}, ...
    {'结果展示 / Result', {
    {'🖼️ 显示参数图', @analysis_showResults, [0.65, 0.45, 0.85]}
    }}, ...
    {'系统 / System', {
    {'🔄重置', @resetAll, [0.85, 0.3, 0.3]}, ...
    {'❓帮助', @showHelp, [0.3, 0.65, 0.92]}
    }}
    };

% 3. 循环创建控件
currentY = 0.92; % 起始Y坐标（从上往下）

for i = 1:length(sections)
    % 取出每一组的数据
    sectTitle = sections{i}{1};
    buttons   = sections{i}{2};
    
    % 创建组标题
    currentY = currentY - headerH;
    createButtonGroupLabel(parent, sectTitle, margins, currentY, 1-2*margins, headerH);
    currentY = currentY - gap;
    
    % 创建该组下的按钮
    for j = 1:length(buttons)
        btnInfo = buttons{j};
        
        currentY = currentY - btnH;
        uicontrol('Parent', parent, 'Style', 'pushbutton', ...
            'String', btnInfo{1}, ...
            'Units', 'normalized', ...
            'Position', [margins+0.02, currentY, 1-2*margins-0.04, btnH], ...
            'FontSize', 10, 'FontWeight', 'bold', ...
            'FontName', 'Microsoft YaHei', ...
            'BackgroundColor', btnInfo{3}, ...
            'ForegroundColor', [1, 1, 1], ...
            'Callback', btnInfo{2});
        currentY = currentY - gap;
    end
    
    % 组间距
    currentY = currentY - sectGap;
end

% 工作日志面板 (放置在底部，占据剩余空间)
logHeight = 0.25;
createWorkLogPanel(parent, 0.01, logHeight);
end

function createButtonGroupLabel(parent, labelText, x, y, w, h)
uicontrol('Parent', parent, 'Style', 'text', ...
    'String', labelText, ...
    'Units', 'normalized', ...
    'Position', [x, y, w, h], ...
    'FontSize', 11, 'FontWeight', 'bold', ...
    'FontName', 'Microsoft YaHei', ...
    'ForegroundColor', [0.3, 0.5, 0.7], ...
    'BackgroundColor', [1, 1, 1], ...
    'HorizontalAlignment', 'left');
end

% Removed createButtonGroup helper as it's now integrated into the main loop
% Removed hardcoded pixel positioning logic

function createWorkLogPanel(parent, bottomY, height)
workLogPanel = uipanel('Parent', parent, ...
    'Title', '操作日志 / Run Log', ...
    'Units', 'normalized', ...
    'Position', [0.02, bottomY, 0.96, height], ...
    'BackgroundColor', [0.97, 0.98, 1], ...
    'ForegroundColor', [0.2, 0.4, 0.6], ...
    'FontSize', 10, ...
    'FontName', 'Microsoft YaHei', ...
    'FontWeight', 'bold');

workLogText = uicontrol('Parent', workLogPanel, ...
    'Style', 'listbox', ...
    'String', {'系统初始化完成', '欢迎使用DSA分析系统'}, ...
    'Units', 'normalized', ...
    'Position', [0.05, 0.25, 0.9, 0.7], ...
    'FontSize', 9, ...
    'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [1, 1, 1], ...
    'ForegroundColor', [0.2, 0.3, 0.4], ...
    'Max', 100, 'Min', 0);

% 按钮行
btnW = 0.28;
btnH = 0.15;
btnY = 0.05;
spacing = 0.03;

uicontrol('Parent', workLogPanel, 'Style', 'pushbutton', ...
    'String', '清空', ...
    'Units', 'normalized', ...
    'Position', [0.05, btnY, btnW, btnH], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.92, 0.4, 0.4], ...
    'ForegroundColor', [1, 1, 1], ...
    'Callback', @log_clearWorkLog);

uicontrol('Parent', workLogPanel, 'Style', 'pushbutton', ...
    'String', '导出', ...
    'Units', 'normalized', ...
    'Position', [0.05+btnW+spacing, btnY, btnW, btnH], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.3, 0.65, 0.92], ...
    'ForegroundColor', [1, 1, 1], ...
    'Callback', @log_exportWorkLog);

uicontrol('Parent', workLogPanel, 'Style', 'pushbutton', ...
    'String', '详细', ...
    'Units', 'normalized', ...
    'Position', [0.05+2*(btnW+spacing), btnY, btnW, btnH], ...
    'FontSize', 9, 'FontName', 'Microsoft YaHei', ...
    'BackgroundColor', [0.35, 0.75, 0.45], ...
    'ForegroundColor', [1, 1, 1], ...
    'Callback', @showDetailedLog);

% 存储工作日志句柄
setappdata(gcf, 'workLogText', workLogText);

% 初始化工作日志数据
workLogData = {
    sprintf('[%s] 系统初始化完成', datestr(now, 'HH:MM:SS'))
    sprintf('[%s] 欢迎使用DSA分析系统 v3.0', datestr(now, 'HH:MM:SS'))
    };
setappdata(gcf, 'workLogData', workLogData);
end

function showDetailedLog(~,~)
workLogData = getappdata(gcf, 'workLogData');
if isempty(workLogData)
    utils_showMessage('工作日志为空', 'error');
    return;
end

logFig = figure('Name', '详细工作日志', ...
    'NumberTitle', 'off', ...
    'Position', [300, 200, 800, 600], ...
    'MenuBar', 'none', ...
    'ToolBar', 'none', ...
    'Color', [0.95, 0.95, 0.95]);

uicontrol('Parent', logFig, 'Style', 'listbox', ...
    'String', workLogData, ...
    'Position', [20, 50, 760, 500], ...
    'FontSize', 10, ...
    'BackgroundColor', [1, 1, 1], ...
    'ForegroundColor', [0.1, 0.1, 0.1], ...
    'Max', 2);

totalEntries = length(workLogData);
todayEntries = sum(contains(workLogData, datestr(now, 'yyyy-mm-dd')));
infoText = sprintf('总日志条目: %d | 今日条目: %d', totalEntries, todayEntries);

uicontrol('Parent', logFig, 'Style', 'text', ...
    'String', infoText, ...
    'Position', [20, 560, 300, 25], ...
    'FontSize', 11, 'FontWeight', 'bold', ...
    'BackgroundColor', [0.95, 0.95, 0.95], ...
    'HorizontalAlignment', 'left');

uicontrol('Parent', logFig, 'Style', 'pushbutton', ...
    'String', '关闭', 'Position', [690, 560, 80, 25], ...
    'FontSize', 10, ...
    'BackgroundColor', [0.8, 0.2, 0.2], ...
    'ForegroundColor', [1, 1, 1], ...
    'Callback', 'delete(gcf)');
end
