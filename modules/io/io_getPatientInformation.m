function patientInfo = io_getPatientInformation(varargin)
    % Moved getPatientInformation into modules/io as io_getPatientInformation
    patientInfo = [];
    dlg = dialog('Name', '患者信息录入', ...
                'WindowStyle', 'normal', ...
                'Position', [500, 400, 400, 400], ...
                'Color', [0.9, 0.95, 1], ...
                'Resize', 'off');
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '患者基本信息录入', ...
             'Position', [50, 350, 300, 30], ...
             'FontSize', 16, 'FontWeight', 'bold', ...
             'ForegroundColor', [0.1, 0.3, 0.6], ...
             'BackgroundColor', [0.9, 0.95, 1], ...
             'HorizontalAlignment', 'center');
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '患者姓名:', 'Position', [50, 300, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    nameEdit = uicontrol('Parent', dlg, 'Style', 'edit', ...
                        'Position', [140, 300, 200, 25], ...
                        'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '病历号:', 'Position', [50, 260, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    idEdit = uicontrol('Parent', dlg, 'Style', 'edit', ...
                      'Position', [140, 260, 200, 25], ...
                      'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '年龄:', 'Position', [50, 220, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    ageEdit = uicontrol('Parent', dlg, 'Style', 'edit', ...
                       'Position', [140, 220, 80, 25], ...
                       'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '性别:', 'Position', [50, 180, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    genderPopup = uicontrol('Parent', dlg, 'Style', 'popupmenu', ...
                           'String', {'男', '女'}, ...
                           'Position', [140, 180, 80, 25], ...
                           'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '临床诊断:', 'Position', [50, 140, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    diagnosisEdit = uicontrol('Parent', dlg, 'Style', 'edit', ...
                             'Position', [140, 140, 200, 25], ...
                             'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'text', ...
             'String', '检查日期:', 'Position', [50, 100, 80, 25], ...
             'FontSize', 11, 'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', 'BackgroundColor', [0.9, 0.95, 1]);
    dateEdit = uicontrol('Parent', dlg, 'Style', 'edit', ...
                        'String', datestr(now, 'yyyy-mm-dd'), ...
                        'Position', [140, 100, 120, 25], ...
                        'FontSize', 11, 'BackgroundColor', [1, 1, 1]);
    uicontrol('Parent', dlg, 'Style', 'pushbutton', ...
             'String', '确认', 'Position', [120, 40, 80, 30], ...
             'FontSize', 12, 'FontWeight', 'bold', ...
             'BackgroundColor', [0.2, 0.7, 0.2], ...
             'ForegroundColor', [1, 1, 1], ...
             'Callback', @confirmCallback);
    uicontrol('Parent', dlg, 'Style', 'pushbutton', ...
             'String', '取消', 'Position', [220, 40, 80, 30], ...
             'FontSize', 12, ...
             'BackgroundColor', [0.8, 0.2, 0.2], ...
             'ForegroundColor', [1, 1, 1], ...
             'Callback', 'delete(gcf)');
    uiwait(dlg);

    function confirmCallback(~,~)
        patientInfo.name = get(nameEdit, 'String');
        patientInfo.id = get(idEdit, 'String');
        patientInfo.age = get(ageEdit, 'String');
        genderOptions = get(genderPopup, 'String');
        patientInfo.gender = genderOptions{get(genderPopup, 'Value')};
        patientInfo.diagnosis = get(diagnosisEdit, 'String');
        patientInfo.date = get(dateEdit, 'String');
        patientInfo.inputTime = datestr(now, 'yyyy-mm-dd HH:MM:SS');
        if isempty(patientInfo.name) || isempty(patientInfo.id)
            errordlg('患者姓名和病历号为必填项！', '输入错误');
            return;
        end
        if ~isempty(patientInfo.age)
            ageNum = str2double(patientInfo.age);
            if isnan(ageNum) || ageNum < 0 || ageNum > 150
                errordlg('请输入有效的年龄！', '输入错误');
                return;
            end
        end
        delete(dlg);
    end
end
