function createInfoArea(parent, patientInfo)
    % 创建右侧信息面板区域
    % 输入: 
    %   parent - 父容器句柄
    %   patientInfo - 患者信息结构体
    
    % 患者信息面板
    patientPanel = uipanel('Parent', parent, ...
                          'Title', '患者信息', ...
                          'Position', [0.05, 0.75, 0.9, 0.24], ...
                          'BackgroundColor', [0.15, 0.25, 0.35], ...
                          'ForegroundColor', [1, 1, 1], ...
                          'FontSize', 11, ...
                          'FontWeight', 'bold');
    
    % 帧控制面板
    framePanel = uipanel('Parent', parent, ...
                        'Title', '帧控制', ...
                        'Position', [0.05, 0.55, 0.9, 0.19], ...
                        'BackgroundColor', [0.15, 0.25, 0.35], ...
                        'ForegroundColor', [1, 1, 1], ...
                        'FontSize', 11, ...
                        'FontWeight', 'bold');
    
    % 分析参数面板
    paramPanel = uipanel('Parent', parent, ...
                        'Title', '灌注参数', ...
                        'Position', [0.05, 0.36, 0.9, 0.19], ...
                        'BackgroundColor', [0.15, 0.25, 0.35], ...
                        'ForegroundColor', [1, 1, 1], ...
                        'FontSize', 11, ...
                        'FontWeight', 'bold');
    
    % 风险评估面板
    riskPanel = uipanel('Parent', parent, ...
                       'Title', '高灌注风险评估', ...
                       'Position', [0.05, 0.05, 0.9, 0.30], ...
                       'BackgroundColor', [0.15, 0.25, 0.35], ...
                       'ForegroundColor', [1, 1, 1], ...
                       'FontSize', 11, ...
                       'FontWeight', 'bold');
    
    % 初始化各面板内容
    initPatientInfoPanel(patientPanel, patientInfo);
    initFrameControlPanel(framePanel);
    initParamPanel(paramPanel);
    initRiskPanel(riskPanel);
end

%% 辅助函数
function initPatientInfoPanel(panel, patientInfo)
    % 初始化患者信息面板
    infoFields = {'姓名:', '病历号:', '年龄:', '性别:', '诊断:', '检查日期:'};
    infoValues = {patientInfo.Name, patientInfo.ID, patientInfo.Age, ...
                 patientInfo.Gender, patientInfo.Diagnosis, patientInfo.StudyDate};
    
    for i = 1:length(infoFields)
        yPos = 160 - (i-1)*22;
        
        uicontrol('Parent', panel, 'Style', 'text', ...
                 'String', infoFields{i}, ...
                 'Position', [10, yPos, 50, 18], ...
                 'FontSize', 10, ...
                 'ForegroundColor', [1, 1, 1], ...
                 'BackgroundColor', [0.15, 0.25, 0.35], ...
                 'HorizontalAlignment', 'left');
        
        uicontrol('Parent', panel, 'Style', 'text', ...
                 'String', infoValues{i}, ...
                 'Position', [65, yPos, 160, 18], ...
                 'FontSize', 10, ...
                 'ForegroundColor', [0.8, 0.9, 1], ...
                 'BackgroundColor', [0.15, 0.25, 0.35], ...
                 'HorizontalAlignment', 'left');
    end
    
    % 数据状态
    uicontrol('Parent', panel, 'Style', 'text', ...
             'String', '数据状态:', ...
             'Position', [10, 30, 50, 18], ...
             'FontSize', 10, ...
             'ForegroundColor', [1, 1, 1], ...
             'BackgroundColor', [0.15, 0.25, 0.35], ...
             'HorizontalAlignment', 'left');
    
    uicontrol('Parent', panel, 'Style', 'text', ...
             'String', '未加载', ...
             'Position', [65, 30, 160, 18], ...
             'FontSize', 10, ...
             'ForegroundColor', [1, 0.8, 0.8], ...
             'BackgroundColor', [0.15, 0.25, 0.35], ...
             'HorizontalAlignment', 'left', ...
             'Tag', 'dataStatus');
end

