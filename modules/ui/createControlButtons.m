function createControlButtons(parent)
% 创建左侧控制按钮面板（极致专业分区版）

% 1. 全局配置
margins = 0.04;     % 左右外边距
panelGap = 0.015;   % 面板间距
btnH = 28;          % 按钮高度缩小以适应屏幕
titleH = 25;        % 标题高度缩小

% 面板主标题 (置顶)
uicontrol('Parent', parent, 'Style', 'text', ...
    'String', '分析控制中枢 | Control Panel', ...
    'Units', 'normalized', ...
    'Position', [0.05, 0.955, 0.9, 0.035], ...
    'FontSize', 12, 'FontWeight', 'bold', ...
    'ForegroundColor', [0.15, 0.3, 0.5], ...
    'BackgroundColor', [1, 1, 1], ...
    'HorizontalAlignment', 'center');

% 2. 定义功能分区及按钮 - 神经支架介入优化版 (Neuro-Stenting Workflow)
% 按照支架手术的客观物理与临床决策流程重新组织
sections = {
    {'基础控制 / BASIC CONTROL', [0.93, 0.97, 1], { ...
        {'📂 打开DICOM数据 (Open File)', @createFileManagerDialog, [0.2, 0.5, 0.8]} ...
    }}, ...
    {'第1步：跨狭窄靶向分析 / TARGETED ANALYSIS', [0.98, 0.95, 0.90], { ...
        {'📍 放置狭窄双端ROI (Proximal/Distal)', @analysis_placeROI, [0.8, 0.6, 0.2]}, ... 
        {'📈 提取双端传导特性 (Extract TDC)', @analysis_extractAndAnalyze, [0.8, 0.6, 0.2]}, ...
        {'⚖️ 跨狭窄血流动力学评估 (TTS & PA)', @analysis_computePressureDrop, [0.8, 0.3, 0.2]} ...
    }}, ...
    {'第2步：全局血流与预警 / GLOBAL FLOW', [0.95, 0.93, 0.98], { ...
        {'🗺️ 像素参数图扫描 (Pixel Map)', @analysis_computeParametricMap, [0.6, 0.4, 0.7]}, ...
        {'🎨 CC-DSA血流动力学编码', @analysis_computeColorCodedDSA, [0.6, 0.4, 0.7]}, ...
        {'🧠 CHS高灌注AI风险评分', @analysis_chsWarning, [0.55, 0.2, 0.65]} ...
    }}, ...
    {'第3步：手术成效量化 / EFFICACY QUANTIFICATION', [0.90, 0.98, 0.90], { ...
        {'📊 术前/术后绝对改善对齐图', @analysis_computeImprovementRate, [0.1, 0.7, 0.3]}, ...
        {'🧠 TDC对比+CHS风险评分报告', @analysis_runComparison, [0.05, 0.5, 0.25]}, ...
        {'💾 保存参比数据', @io_savePreData, [0.3, 0.5, 0.7]}, ...
        {'📝 导出支架成效评估报告', @io_exportData, [0.3, 0.6, 0.7]} ...
    }}, ...
    {'系统维护 / SYSTEM', [1, 0.95, 0.95], { ...
        {'🔄 系统重置 Reset', @resetAll, [0.85, 0.3, 0.3]} ...
    }}
};

% 3. 动态布局计算与渲染 (纯归一化坐标修正版)
% 顶部标题占用空间: topY 开始，占用 titleSpace
topY = 0.96;

% 底部日志面板占用空间: bottomY 起始，高度 logHeight
logHeight = 0.16;
bottomY = 0.01;

% 中间可用于分配控制面板的绝对总高度 (归一化)
% 必须减去面板之间的总间隙，否则下方面板会被推挤覆盖
totalGaps = (length(sections) - 1) * panelGap;
availableSpace = topY - (bottomY + logHeight) - 0.02 - totalGaps; 

% 按照各个板块中按钮的数量来计算权重，从而动态分配每个板块的高度
totalBtns = 0;
for i = 1:length(sections)
    totalBtns = totalBtns + length(sections{i}{3});
end

% 基础高度(代表板块标题) + 按钮高度权重
% 假设每个标题相对一个按钮的权重是 1.2
titleWeight = 1.2;
totalWeight = length(sections) * titleWeight + totalBtns;

currentY = topY; % 从上往下画

for i = 1:length(sections)
    sectTitle = sections{i}{1};
    sectColor = sections{i}{2};
    buttons   = sections{i}{3};
    numBtns   = length(buttons);
    
    % 计算当前面板应该分得的高度比例
    panelWeight = titleWeight + numBtns;
    panelNormH = availableSpace * (panelWeight / totalWeight);
    
    % 计算出当前面板的起始 Y (面板的左下角坐标)
    currentY = currentY - panelNormH;
    
    % A. 创建功能分区面板
    groupPanel = uipanel('Parent', parent, ...
        'Title', sectTitle, ...
        'Units', 'normalized', ...
        'Position', [margins, currentY, 1-2*margins, panelNormH], ...
        'BackgroundColor', sectColor, ...
        'ForegroundColor', [0.2, 0.3, 0.5], ...
        'FontSize', 10, 'FontWeight', 'bold', ...
        'BorderType', 'line', 'HighlightColor', [0.8, 0.8, 0.9]);
    
    % B. 面板内创建按钮 (垂直分布，子节点归一化空间是 0~1)
    topPad = 0.15; % 顶部留出标题空间
    bottomPad = 0.08; % 底部留空
    availableH = 1.0 - topPad - bottomPad;
    
    if numBtns > 1
        gap = 0.05; % 按钮间隙
    else
        gap = 0;
    end
    
    btnNormH = (availableH - (numBtns-1)*gap) / numBtns;
    
    for j = 1:numBtns
        btnInfo = buttons{j};
        
        % 面板内部坐标系 (0到1)，按从上到下排列
        yPos = 1.0 - topPad - j*btnNormH - (j-1)*gap;
        
        uicontrol('Parent', groupPanel, 'Style', 'pushbutton', ...
            'String', btnInfo{1}, ...
            'Units', 'normalized', ...
            'Position', [0.05, yPos, 0.9, btnNormH], ...
            'FontSize', 10, 'FontWeight', 'bold', ...
            'BackgroundColor', btnInfo{3}, ...
            'ForegroundColor', [1, 1, 1], ...
            'Callback', btnInfo{2});
    end
    
    % 面板之间的间隙
    currentY = currentY - panelGap;
end

% 工作日志面板 (放置在底部)
createWorkLogPanel(parent, bottomY, logHeight);
end

