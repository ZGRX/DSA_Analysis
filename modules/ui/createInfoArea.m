function value = getFieldOrDefault(struct, fieldName, defaultValue, isNumeric)
% 获取结构体字段值，如果不存在则返回默认值
if nargin < 4
    isNumeric = false;
end

if isfield(struct, fieldName) && ~isempty(struct.(fieldName))
    if isNumeric
        % 年龄字段可能是字符串或数字
        if isnumeric(struct.(fieldName))
            value = sprintf('%d岁', struct.(fieldName));
        else
            value = sprintf('%s岁', struct.(fieldName));
        end
    else
        value = struct.(fieldName);
    end
else
    value = defaultValue;
end
end
